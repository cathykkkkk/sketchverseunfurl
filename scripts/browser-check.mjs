import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.route('**/geocoding-api.open-meteo.com/**',route=>route.fulfill({json:{results:[{name:'里斯本',country_code:'PT',admin1:'里斯本'}]}}));
await page.goto('http://localhost:5173/');
await page.getByRole('textbox',{name:'搜索城市或国家'}).fill('里斯本');
await page.getByRole('button',{name:/里斯本 葡萄牙/}).click();
await page.locator('input[type="date"]').fill('2019-05-04');
await page.locator('input[type="number"]').fill('3');
await page.getByRole('button',{name:'保存这段旅程'}).click();
assert.equal(await page.locator('[data-country="PT"]').getAttribute('fill'),'#7eb49b');
await page.reload();await page.getByRole('heading',{name:'里斯本',exact:true}).waitFor();
await page.getByRole('button',{name:'修改里斯本'}).click();await page.locator('input[type="number"]').fill('11');await page.getByRole('button',{name:'保存这段旅程'}).click();
assert.equal(await page.locator('[data-country="PT"]').getAttribute('fill'),'#205a47');
await page.getByRole('button',{name:'按首次年份'}).click();assert.match(await page.locator('[data-country="PT"]').getAttribute('fill'),/^hsl/);
await page.screenshot({path:'/tmp/atlas-desktop.png',fullPage:true});
page.on('dialog',dialog=>dialog.accept());await page.getByRole('button',{name:'删除里斯本'}).click();assert.equal(await page.locator('[data-country="PT"]').getAttribute('fill'),'#e6e8e1');
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'/tmp/atlas-mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
assert.deepEqual(errors,[]);console.log('PASS: city country mapping, creation, persistence, editing, color modes, deletion, mobile overflow; no browser errors');await browser.close();
